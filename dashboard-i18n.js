function dashboardLanguage() {
  return document.documentElement.lang === 'en' ? 'en' : 'cs';
}

function dashboardText(czech) {
  return dashboardLanguage() === 'en' && Object.hasOwn(DASHBOARD_ENGLISH, czech)
    ? DASHBOARD_ENGLISH[czech] : czech;
}

function dashboardLocale() {
  return dashboardLanguage() === 'en' ? 'en-GB' : 'cs-CZ';
}

function changeDashboardLanguage(select) {
  const previous = dashboardLanguage();
  const next = select.value;
  if (!['cs', 'en'].includes(next) || next === previous) { select.value = previous; return; }
  // Reload only after confirmation, so in-flight requests and unsaved forms are not silently lost.
  if (!window.confirm(dashboardText('Změnit jazyk? Stránka se obnoví a neuložené změny se zahodí.'))) {
    select.value = previous;
    return;
  }
  try {
    localStorage.setItem('dashboardLanguage', next);
  } catch {
    select.value = previous;
    window.alert(dashboardText('Jazyk se nepodařilo uložit. Povol úložiště prohlížeče a zkus to znovu.'));
    return;
  }
  location.reload();
}

function initializeDashboardLanguage() {
  let language = 'cs';
  try {
    if (localStorage.getItem('dashboardLanguage') === 'en') language = 'en';
  } catch { /* Czech remains available when storage is blocked. */ }
  document.documentElement.lang = language;
  document.querySelectorAll('[data-dashboard-language]').forEach(select => { select.value = language; });
  // Run once, before dashboard.js can insert any restaurant, menu or guest data.
  // Translating direct text nodes preserves nested inputs, buttons, icons and event handlers.
  document.querySelectorAll('[data-dashboard-i18n]').forEach(element => {
    for (const node of element.childNodes) {
      if (node.nodeType !== 3) continue;
      const key = node.textContent.trim().replace(/\s+/g, ' ');
      if (Object.hasOwn(DASHBOARD_ENGLISH, key)) {
        node.textContent = node.textContent.replace(node.textContent.trim(), dashboardText(key));
      }
    }
    for (const attribute of ['aria-label', 'title', 'placeholder', 'alt']) {
      const value = element.getAttribute(attribute);
      if (value && Object.hasOwn(DASHBOARD_ENGLISH, value)) element.setAttribute(attribute, dashboardText(value));
    }
  });
}

